describe('AC-4 TOC parser (shaka-faithful)', () => {
	test('parseAc4TocSizeBits matches shaka on the reference frame (906 bits)', () => {
		expect(parseAc4TocSizeBits(VALID_AC4_DATA)).toBe(906);
	});

	test('parseAc4TocSizeBits returns null on invalid data', () => {
		expect(parseAc4TocSizeBits(Uint8Array.from([0x00, 0x00, 0x00, 0x00]))).toBeNull();
	});

	// shaka's SetupProtectionPattern applies the crypt/skip pattern to AC-4 (like video), unlike other
	// audio which is whole-block full-sample encrypted. A 1200-byte frame (real TOC prefix + zero pad)
	// clears 912 bytes (round8 of 906 bits) and leaves a 288-byte cipher region where the pattern shows.
	const ac4AudioFrame = (): Uint8Array => {
		const frame = new Uint8Array(1200);
		frame.set(VALID_AC4_DATA, 0);
		return frame;
	};
	const AC4_STREAM_INFO = { codec: 'ac4' as const, codecConfig: new Uint8Array(0), naluLengthSize: 0 as const };
	const zeroBlock = (data: Uint8Array, byteOffset: number): boolean =>
		data.subarray(byteOffset, byteOffset + 16).every(b => b === 0);

	test('AC-4 cbcs applies the 1:9 pattern over the cipher region', () => {
		const enc = new SampleEncryptor({
			streamInfo: AC4_STREAM_INFO, streamType: 'audio', scheme: 'cbcs',
			key: new Uint8Array(16).fill(0x2b), iv: new Uint8Array(16).fill(0x11),
		});
		const { data, subsamples } = enc.encryptSample(ac4AudioFrame());
		expect(subsamples).toEqual([{ clearBytes: 912, cipherBytes: 288 }]);
		// crypt 1 block, skip 9: within the 288-byte (18-block) cipher region only blocks 0 and 10 encrypt.
		expect(zeroBlock(data, 912 + 0 * 16)).toBe(false); // crypted
		for (let n = 1; n <= 9; n++) {
			expect(zeroBlock(data, 912 + n * 16)).toBe(true); // skipped → still zero padding
		}
		expect(zeroBlock(data, 912 + 10 * 16)).toBe(false); // crypted
		for (let n = 11; n <= 17; n++) {
			expect(zeroBlock(data, 912 + n * 16)).toBe(true); // skipped
		}
	});

	test('AC-4 cenc has no pattern — the whole cipher region is encrypted', () => {
		const enc = new SampleEncryptor({
			streamInfo: AC4_STREAM_INFO, streamType: 'audio', scheme: 'cenc',
			key: new Uint8Array(16).fill(0x2b), iv: new Uint8Array(8).fill(0x11),
		});
		const { data } = enc.encryptSample(ac4AudioFrame());
		// No pattern: a block that cbcs would skip (block 5) is encrypted here.
		expect(zeroBlock(data, 912 + 5 * 16)).toBe(false);
	});
});

