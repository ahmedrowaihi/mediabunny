import { describe, expect, test } from 'vitest';
import { H265VideoSliceHeaderParser } from '../../src/crypto/h265-slice-header-parser.js';
import type { Nalu } from '../../src/crypto/subsample-generator.js';

// hvcC extra data (VPS + SPS + PPS), from the shaka unittest.
const kExtraData = new Uint8Array([
	0x01, 0x01, 0x40, 0x00, 0x00, 0x00, 0x90, 0x00, 0x00, 0x00, 0x00, 0x00,
	0x96, 0xF0, 0x00, 0xFC, 0xFD, 0xF8, 0xF8, 0x00, 0x00, 0x0F, 0x03,
	// VPS
	0x20, 0x00, 0x01, 0x00, 0x17,
	0x40, 0x01, 0x0C, 0x01, 0xFF, 0xFF, 0x01, 0x40, 0x00, 0x00, 0x03, 0x00,
	0x90, 0x00, 0x00, 0x03, 0x00, 0x00, 0x03, 0x00, 0x96, 0xBC, 0x09,
	// SPS
	0x21, 0x00, 0x01, 0x00, 0x2D,
	0x42, 0x01, 0x01, 0x01, 0x40, 0x00, 0x00, 0x03, 0x00, 0x90, 0x00, 0x00,
	0x03, 0x00, 0x00, 0x03, 0x00, 0x96, 0xA0, 0x03, 0xC0, 0x80, 0x11, 0x07,
	0xCB, 0x96, 0xF4, 0xA4, 0x21, 0x19, 0x3F, 0x8C, 0x04, 0x04, 0x00, 0x00,
	0x03, 0x00, 0x04, 0x00, 0x00, 0x03, 0x01, 0x68, 0x20,
	// PPS
	0x22, 0x00, 0x01, 0x00, 0x08,
	0x44, 0x01, 0xC0, 0xAD, 0xF0, 0x33, 0x24, 0x00,
]);

const kDataIntra = new Uint8Array([0x26, 0x01, 0xAF, 0x2E, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF]);
const kDataInter = new Uint8Array([0x02, 0x01, 0xD0, 0x08, 0xBF, 0xA5, 0xC0, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF]);

const nalu = (data: Uint8Array): Nalu => ({
	type: (data[0]! >> 1) & 0x3f,
	headerSize: 2,
	payloadSize: data.length - 2,
	isVideoSlice: true,
	data,
});

describe('H265VideoSliceHeaderParser', () => {
	// shaka: TEST(H265VideoSliceHeaderParserTest, BasicSupport)
	test('computes slice-header sizes (intra → 2 bytes, inter → 5 bytes)', () => {
		const parser = new H265VideoSliceHeaderParser();
		expect(parser.initialize(kExtraData)).toBe(true);
		expect(parser.getHeaderSize(nalu(kDataIntra))).toBe(2);
		expect(parser.getHeaderSize(nalu(kDataInter))).toBe(5);
	});
});
